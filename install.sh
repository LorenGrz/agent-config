#!/usr/bin/env bash
# Install / repair agent-config on this machine.
#
# Layout it builds (see docs/decisions/0006-neutral-agents-layer.md):
#
#   <hub>  (this repo, cloned anywhere — NOT ~/.agents/skills)
#     └─ source of truth, edited by hand
#
#   ~/.agents/            tool-neutral runtime, owned by this script
#     AGENTS.md           generated: config/AGENTS.md + your profile
#     skills/<name>       flat links to <hub>/skills/<category>/<name>
#     rules   -> <hub>/config/rules
#     hooks   -> <hub>/config/hooks
#     models.env -> <hub>/config/models.env
#
#   Per-tool adapters (symlinks into ~/.agents, except Claude's CLAUDE.md):
#     Claude Code  ~/.claude/{skills,rules,hooks} -> ~/.agents/...
#                  ~/.claude/agents -> <hub>/config/agents
#                  ~/.claude/CLAUDE.md (generated: @~/.agents/AGENTS.md + config/CLAUDE.md)
#                  ~/.claude/settings.json (config/settings.base.json merged in)
#     Codex        ~/.codex/AGENTS.md -> ~/.agents/AGENTS.md  (skills: native ~/.agents/skills)
#                  + `codex` MCP server registered in Claude Code, if codex is installed
#     OpenCode     ~/.config/opencode/AGENTS.md -> ~/.agents/AGENTS.md (skills: native)
#     oc-ask       ~/.local/bin/oc-ask -> <hub>/bin/oc-ask
#
#   Removing a tool = deleting its symlinks; ~/.agents/ is untouched.
#
# Idempotent and safe: never deletes a real file or directory. A real file/dir
# we don't own is moved aside to <path>.bak.<timestamp> once, then relinked.
# Files carrying the "generated by agent-config install.sh" header are ours and
# are replaced silently.
#
# Profile resolution (which config/profiles/<name>.md to use), in order:
#   1. --profile <name>
#   2. ~/.config/agent-config/profile (persisted by a previous run)
#   3. `gh api user --jq .login`, lowercased, if config/profiles/<login>.md exists
#   4. same login with no profile yet: copy config/profiles/_template.md to it
#   5. config/profiles/_template.md itself
#
# Usage:
#   ./install.sh [--profile <name>] [--dry-run] [--with-rtk] [--with-rulesync]
#
#   --profile <name> use config/profiles/<name>.md instead of auto-detecting
#   --dry-run        print planned actions only, change nothing
#   --with-rtk       also install rtk (https://github.com/rtk-ai/rtk); hook: config/hooks/rtk.sh
#   --with-rulesync  also (re)generate Cursor / Antigravity config via config/rulesync/

set -euo pipefail

HUB="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export AGENT_CONFIG_HOME="$HUB"
AGENTS_DIR="${AGENTS_DIR:-$HOME/.agents}"
CLAUDE_DIR="${CLAUDE_DIR:-$HOME/.claude}"
CODEX_DIR="${CODEX_DIR:-$HOME/.codex}"
OPENCODE_DIR="${OPENCODE_DIR:-$HOME/.config/opencode}"
BIN_DIR="${BIN_DIR:-$HOME/.local/bin}"
PROFILE_STATE_DIR="${AGENT_CONFIG_STATE_DIR:-$HOME/.config/agent-config}"
PROFILE_STATE_FILE="$PROFILE_STATE_DIR/profile"
GENERATED_MARK="generated by agent-config install.sh"

DRY_RUN=0
WITH_RTK=0
WITH_RULESYNC=0
PROFILE_FLAG=""

while [ $# -gt 0 ]; do
  case "$1" in
    --profile) PROFILE_FLAG="$2"; shift 2 ;;
    --dry-run) DRY_RUN=1; shift ;;
    --with-rtk) WITH_RTK=1; shift ;;
    --with-rulesync) WITH_RULESYNC=1; shift ;;
    -h|--help)
      sed -n '2,46p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
      exit 0
      ;;
    *)
      echo "unknown flag: $1" >&2
      exit 1
      ;;
  esac
done

ts() { date +%Y%m%d%H%M%S; }
run() { if [ "$DRY_RUN" -eq 1 ]; then echo "  [dry-run] $*"; else "$@"; fi; }

# ---------------------------------------------------------------------------
# Old layout guard: the hub used to be cloned AT ~/.agents/skills. That path is
# now the flat skills dir Codex and OpenCode read natively, so the hub can't
# live there. We never move a git checkout ourselves.
# ---------------------------------------------------------------------------
if [ "$HUB" = "$AGENTS_DIR/skills" ] || [ -d "$AGENTS_DIR/skills/.git" ]; then
  cat >&2 <<EOF
The hub is cloned at $AGENTS_DIR/skills (old layout). Move it first, then re-run:

  mv "$AGENTS_DIR/skills" ~/projects/agent-config
  ~/projects/agent-config/install.sh --dry-run

(Any symlinked skills you kept in that folder — omarchy, apexlang, ... — move with it
and keep working: install.sh links top-level skill symlinks in the hub root too.)
EOF
  exit 1
fi

# ---------------------------------------------------------------------------
# Profile resolution
# ---------------------------------------------------------------------------
resolve_profile() {
  if [ -n "$PROFILE_FLAG" ]; then printf '%s' "$PROFILE_FLAG"; return; fi
  if [ -f "$PROFILE_STATE_FILE" ]; then printf '%s' "$(cat "$PROFILE_STATE_FILE")"; return; fi

  if command -v gh >/dev/null 2>&1; then
    local login
    login="$(gh api user --jq .login 2>/dev/null | tr '[:upper:]' '[:lower:]' || true)"
    if [ -n "$login" ]; then
      if [ -f "$HUB/config/profiles/$login.md" ]; then printf '%s' "$login"; return; fi
      echo "no profile for GitHub login '$login' yet — copying config/profiles/_template.md to config/profiles/$login.md" >&2
      if [ "$DRY_RUN" -eq 1 ]; then
        echo "  [dry-run] cp '$HUB/config/profiles/_template.md' '$HUB/config/profiles/$login.md'" >&2
      else
        cp "$HUB/config/profiles/_template.md" "$HUB/config/profiles/$login.md"
      fi
      echo "fill in config/profiles/$login.md, then re-run this script." >&2
      printf '%s' "$login"; return
    fi
  fi
  printf '_template'
}

PROFILE="$(resolve_profile)"
PROFILE_FILE="$HUB/config/profiles/$PROFILE.md"

if [ ! -f "$PROFILE_FILE" ]; then
  if [ "$DRY_RUN" -eq 1 ]; then
    echo "note:    $PROFILE_FILE does not exist yet (dry-run) — previewing with config/profiles/_template.md"
    PROFILE_FILE="$HUB/config/profiles/_template.md"
  else
    echo "profile not found: $PROFILE_FILE" >&2
    echo "create it (cp '$HUB/config/profiles/_template.md' '$PROFILE_FILE') or re-run with --profile <existing-name>." >&2
    exit 1
  fi
fi

echo "== profile: $PROFILE ($PROFILE_FILE) =="
if [ "$DRY_RUN" -eq 1 ]; then
  echo "  [dry-run] write '$PROFILE' to '$PROFILE_STATE_FILE'"
else
  mkdir -p "$PROFILE_STATE_DIR"
  printf '%s\n' "$PROFILE" > "$PROFILE_STATE_FILE"
fi

# ---------------------------------------------------------------------------
# link <target> <link_path> — create or repair a symlink. A real file/dir is
# backed up, except a file we generated earlier (replaced silently).
# ---------------------------------------------------------------------------
link() {
  local target="$1" link_path="$2"

  if [ -L "$link_path" ]; then
    if [ "$(readlink "$link_path")" = "$target" ]; then
      echo "ok:      $link_path -> $target"; return
    fi
    echo "repair:  $link_path (was -> $(readlink "$link_path"))"
    run rm -f "$link_path"
  elif [ -f "$link_path" ] && grep -q "$GENERATED_MARK" "$link_path" 2>/dev/null; then
    echo "replace: $link_path (old generated file)"
    run rm -f "$link_path"
  elif [ -e "$link_path" ]; then
    local backup="${link_path}.bak.$(ts)"
    echo "backup:  $link_path -> $backup (real file/dir, not deleted)"
    run mv "$link_path" "$backup"
  else
    echo "create:  $link_path -> $target"
  fi
  run mkdir -p "$(dirname "$link_path")"
  run ln -s "$target" "$link_path"
}

# ---------------------------------------------------------------------------
# write_generated <dest> <content> — write a file we own (GENERATED_MARK).
# ---------------------------------------------------------------------------
write_generated() {
  local dest="$1" content="$2"

  if [ -L "$dest" ]; then
    echo "replace symlink: $dest (was -> $(readlink "$dest"))"
    run rm -f "$dest"
  elif [ -e "$dest" ] && ! grep -q "$GENERATED_MARK" "$dest" 2>/dev/null; then
    local backup="${dest}.bak.$(ts)"
    echo "backup:  $dest -> $backup (real file, not generated by us)"
    run mv "$dest" "$backup"
  fi

  if [ -f "$dest" ] && [ "$(cat "$dest" 2>/dev/null)" = "$content" ]; then
    echo "ok:      $dest already up to date"; return
  fi

  echo "generate: $dest"
  if [ "$DRY_RUN" -eq 1 ]; then
    echo "  [dry-run] write generated content to '$dest'"
  else
    mkdir -p "$(dirname "$dest")"
    printf '%s\n' "$content" > "$dest"
  fi
}

# ---------------------------------------------------------------------------
# 1. Neutral layer: ~/.agents
# ---------------------------------------------------------------------------
echo
echo "== neutral layer: $AGENTS_DIR =="

agents_md_content="$(
  printf '<!-- %s — edit the repo, not this file. -->\n\n' "$GENERATED_MARK"
  cat "$HUB/config/AGENTS.md"
  printf '\n\n'
  cat "$PROFILE_FILE"
)"
write_generated "$AGENTS_DIR/AGENTS.md" "$agents_md_content"
link "$HUB/config/rules"      "$AGENTS_DIR/rules"
link "$HUB/config/hooks"      "$AGENTS_DIR/hooks"
link "$HUB/config/models.env" "$AGENTS_DIR/models.env"

# Flat skills dir: one link per skills/<category>/<name>/SKILL.md, plus any
# top-level symlinked skill in the hub root (external skills you keep there,
# e.g. omarchy, apexlang — gitignored).
SKILLS_DIR="$AGENTS_DIR/skills"
if [ -L "$SKILLS_DIR" ] || { [ -e "$SKILLS_DIR" ] && [ ! -d "$SKILLS_DIR" ]; }; then
  echo "backup:  $SKILLS_DIR -> $SKILLS_DIR.bak.$(ts) (not a plain directory)"
  run mv "$SKILLS_DIR" "$SKILLS_DIR.bak.$(ts)"
fi
run mkdir -p "$SKILLS_DIR"

created=0 updated=0 pruned=0
while IFS= read -r skill_md; do
  dir="$(dirname "$skill_md")"
  name="$(basename "$dir")"
  dest="$SKILLS_DIR/$name"
  if [ -L "$dest" ]; then
    [ "$(readlink "$dest")" = "$dir" ] && continue
    run rm -f "$dest"; run ln -s "$dir" "$dest"; updated=$((updated+1))
  elif [ -e "$dest" ]; then
    echo "skip:    $dest exists and is not a symlink" >&2
  else
    run ln -s "$dir" "$dest"; created=$((created+1))
  fi
done < <(
  find "$HUB/skills" -mindepth 3 -maxdepth 3 -name SKILL.md
  for ext in "$HUB"/*; do [ -L "$ext" ] && [ -f "$ext/SKILL.md" ] && printf '%s\n' "$ext/SKILL.md"; done
)

# Prune links into the hub that no longer resolve (moved/deleted skills).
for dest in "$SKILLS_DIR"/*; do
  [ -L "$dest" ] || continue
  case "$(readlink "$dest")" in
    "$HUB"/*) [ -e "$dest" ] || { run rm -f "$dest"; pruned=$((pruned+1)); } ;;
  esac
done
echo "skills:  $SKILLS_DIR (created $created, updated $updated, pruned $pruned)"

# ---------------------------------------------------------------------------
# 2. Claude Code adapter
# ---------------------------------------------------------------------------
echo
echo "== Claude Code: $CLAUDE_DIR =="

claude_md_content="$(cat <<EOF
<!-- $GENERATED_MARK — edit the repo, not this file. -->
@$AGENTS_DIR/AGENTS.md
@$HUB/config/CLAUDE.md
EOF
)"
write_generated "$CLAUDE_DIR/CLAUDE.md" "$claude_md_content"
link "$AGENTS_DIR/skills" "$CLAUDE_DIR/skills"
link "$AGENTS_DIR/rules"  "$CLAUDE_DIR/rules"
link "$AGENTS_DIR/hooks"  "$CLAUDE_DIR/hooks"
link "$HUB/config/agents" "$CLAUDE_DIR/agents"

SETTINGS="$CLAUDE_DIR/settings.json"
BASE="$HUB/config/settings.base.json"
if [ ! -f "$SETTINGS" ]; then
  echo "create:  $SETTINGS"
  run mkdir -p "$CLAUDE_DIR"
  run cp "$BASE" "$SETTINGS"
else
  # hooks / enabledPlugins / extraKnownMarketplaces / model / theme: base wins.
  # permissions.allow / ask: union. Everything else (statusLine, env, ...) is yours.
  MERGED="$(jq -s '
    .[0] as $cur | .[1] as $base
    | $cur
    | .model = $base.model
    | .hooks = $base.hooks
    | .enabledPlugins = $base.enabledPlugins
    | .extraKnownMarketplaces = $base.extraKnownMarketplaces
    | .theme = $base.theme
    | .permissions.allow = ((($cur.permissions.allow // []) + ($base.permissions.allow // [])) | unique)
    | .permissions.ask   = ((($cur.permissions.ask   // []) + ($base.permissions.ask   // [])) | unique)
  ' "$SETTINGS" "$BASE")"
  if [ "$(jq -S . "$SETTINGS")" = "$(jq -S . <<<"$MERGED")" ]; then
    echo "ok:      $SETTINGS already up to date"
  else
    BACKUP="$SETTINGS.bak.$(ts)"
    echo "backup:  $SETTINGS -> $BACKUP, then merge config/settings.base.json"
    if [ "$DRY_RUN" -eq 0 ]; then
      cp "$SETTINGS" "$BACKUP"
      jq . <<<"$MERGED" >"$SETTINGS"
    fi
  fi
fi

# ---------------------------------------------------------------------------
# 3. Codex adapter (instructions always; MCP tier only if codex is installed)
# ---------------------------------------------------------------------------
echo
echo "== Codex: $CODEX_DIR =="
link "$AGENTS_DIR/AGENTS.md" "$CODEX_DIR/AGENTS.md"
echo "skills:  native ($AGENTS_DIR/skills)"

if command -v codex >/dev/null 2>&1 && command -v claude >/dev/null 2>&1; then
  if claude mcp get codex >/dev/null 2>&1; then
    echo "ok:      codex MCP server already registered in Claude Code"
  else
    echo "add:     codex MCP server to Claude Code (user scope)"
    run claude mcp add -s user codex -- codex mcp-server \
      || echo "warn:    'claude mcp add' failed — register it by hand: claude mcp add -s user codex -- codex mcp-server" >&2
  fi
  echo "note:    run 'codex login' once if you haven't (uses your ChatGPT plan)."
  echo "note:    for automatic HANDOFF.md snapshots from Codex, add to $CODEX_DIR/config.toml:"
  echo "           notify = [\"bash\", \"$AGENTS_DIR/hooks/handoff.sh\", \"snapshot\", \"codex\"]"
else
  echo "skip:    codex (or claude) not on PATH — deep-worker tier disabled."
fi

# ---------------------------------------------------------------------------
# 4. OpenCode adapter + oc-ask
# ---------------------------------------------------------------------------
echo
echo "== OpenCode: $OPENCODE_DIR =="
if command -v opencode >/dev/null 2>&1 || [ -d "$OPENCODE_DIR" ]; then
  link "$AGENTS_DIR/AGENTS.md" "$OPENCODE_DIR/AGENTS.md"
  echo "skills:  native ($AGENTS_DIR/skills)"
else
  echo "skip:    opencode not installed — oc-ask will exit 3 and Claude falls back to its own agents."
fi
link "$HUB/bin/oc-ask" "$BIN_DIR/oc-ask"
case ":$PATH:" in *":$BIN_DIR:"*) ;; *) echo "note:    add $BIN_DIR to your PATH for oc-ask." ;; esac

# Antigravity (Gemini) reads skills from its own dir — point it at the neutral one.
if [ -d "$HOME/.gemini" ] && [ ! -e "$HOME/.gemini/config/skills" ]; then
  link "$AGENTS_DIR/skills" "$HOME/.gemini/config/skills"
fi

# ---------------------------------------------------------------------------
# Optional extras
# ---------------------------------------------------------------------------
if [ "$WITH_RULESYNC" -eq 1 ]; then
  echo
  echo "== rulesync (antigravity-cli, cursor) =="
  run "$HUB/config/rulesync/build.sh"
  if [ "$DRY_RUN" -eq 1 ]; then
    echo "  [dry-run] (cd config/rulesync && pnpm dlx rulesync generate)"
  else
    (cd "$HUB/config/rulesync" && pnpm dlx rulesync generate)
  fi
fi

if [ "$WITH_RTK" -eq 1 ]; then
  echo
  echo "== rtk =="
  RTK_CMD='curl -fsSL https://raw.githubusercontent.com/rtk-ai/rtk/refs/heads/master/install.sh | sh'
  run sh -c "$RTK_CMD"
  echo "rtk hook is wired via config/hooks/rtk.sh (settings.base.json); restart Claude Code."
fi

echo
echo "hub:     $HUB"
echo "neutral: $AGENTS_DIR"
echo "hint:    'npx ccusage@latest' shows Claude usage; edit config/models.env to change the cheap model."
